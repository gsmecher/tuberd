#!/usr/bin/env python3

"""
These tests exercise TuberClient code against canned responses.  This allows us
to test edge cases / "unhappy path" code that's not generated by this version
of the server-side code.
"""

import aiohttp.web
import asyncio
import json
import pytest
import pytest_asyncio
import tuber


# On the test's own loop: a fixture on the module loop (this project's default)
# could not answer a test awaiting on a function loop.
@pytest_asyncio.fixture(scope="function", loop_scope="function")
async def canned_server():
    """Serve queued responses, one per request, on an ephemeral port.

    Yields (responses, host): append JSON strings to ``responses`` before
    making requests.
    """
    responses = []

    app = aiohttp.web.Application()

    async def handler(request):
        return aiohttp.web.Response(text=responses.pop(0), content_type="application/json")

    app.router.add_post("/tuber", handler)

    runner = aiohttp.web.AppRunner(app)
    await runner.setup()

    # One address: "localhost" would bind a socket per address it resolves
    # to, each on its own ephemeral port, and a client resolving it the other
    # way around would knock on the wrong one.
    site = aiohttp.web.TCPSite(runner, host="127.0.0.1", port=0)
    await site.start()

    yield responses, "127.0.0.1:%d" % runner.addresses[0][1]

    await runner.cleanup()


async def resolve(obj):
    """Resolve either client's object while the canned server keeps serving."""
    if isinstance(obj, tuber.TuberObject):
        await obj.tuber_resolve()
    else:
        await asyncio.get_running_loop().run_in_executor(None, obj.tuber_resolve)


LEGACY_METHOD = {"__doc__": "some_method", "__signature__": "(x)"}
METHOD = {"__doc__": None, "__signature__": {"parameters": []}}


@pytest.mark.parametrize("cls", [tuber.TuberObject, tuber.SimpleTuberObject])
@pytest.mark.parametrize(
    "response, descriptions",
    [
        pytest.param({}, [], id="void_object"),
        pytest.param({"methods": None}, [], id="null_for_methods"),
        pytest.param({"properties": None}, [], id="null_for_properties"),
        pytest.param({"methods": []}, [], id="empty_list_for_methods"),
        pytest.param({"properties": []}, [], id="empty_list_for_properties"),
        # tuberd v0.15 and older list names, which the client then asks it to
        # describe in a second request
        pytest.param({"methods": ["some_method"]}, [LEGACY_METHOD], id="populated_list_for_methods"),
        pytest.param({"properties": ["some_property"]}, [42], id="populated_list_for_properties"),
        pytest.param(
            {"__doc__": None, "methods": {"some_method": METHOD}, "properties": {"some_property": 42}, "objects": {}},
            [],
            id="fancy",
        ),
    ],
)
@pytest.mark.asyncio
async def test_basic_resolve(canned_server, cls, response, descriptions):
    """
    Does tuber_resolve() cope with every metadata shape a server may send?
    """

    responses, host = canned_server
    responses.append(json.dumps([{"result": response}]))
    if descriptions:
        responses.append(json.dumps([{"result": d} for d in descriptions]))

    obj = cls("ObjectNameIsIgnored", hostname=host)
    await resolve(obj)

    assert not responses, "every canned response was consumed"
    if response.get("methods"):
        assert callable(obj.some_method)
    if response.get("properties"):
        assert obj.some_property == 42

    if isinstance(obj, tuber.SimpleTuberObject) and not isinstance(obj, tuber.TuberObject):
        obj.close()
